// Minimal, dependency-free bundler for Folio's own TypeScript sources.
//
// Folio deliberately has no npm dependencies. This bundler supports only the
// constrained module style used in src/: named `import { a, b as c } from './x.ts'`,
// `import * as ns from './x.ts'`, `import type ...` (erased), and
// `export function|async function|const|let|class name`. Anything else fails the
// build loudly instead of producing a subtly broken bundle.
//
// Types are removed with Node's built-in `module.stripTypeScriptTypes` (strip
// mode: erasable syntax only, no type checking). Output is a single classic-script
// IIFE, which MV3 content scripts require.

import { readFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { stripTypeScriptTypes } from 'node:module';

const IDENT = '[A-Za-z_$][\\w$]*';
const NAMED_IMPORT = new RegExp(`^import\\s*\\{([^}]*)\\}\\s*from\\s*(['"])([^'"]+)\\2;?`, 'gm');
const NS_IMPORT = new RegExp(`^import\\s*\\*\\s*as\\s+(${IDENT})\\s+from\\s*(['"])([^'"]+)\\2;?`, 'gm');
const BARE_IMPORT = /^import\s*(['"])([^'"]+)\1;?/gm;
const EXPORT_DECL = new RegExp(`^export\\s+((?:async\\s+)?function\\*?|const|let|class)\\s+(${IDENT})`, 'gm');

function toId(root, file) {
  return relative(root, file).split(sep).join('/');
}

function stripTypes(file, source) {
  if (!file.endsWith('.ts')) return source;
  try {
    return stripTypeScriptTypes(source, { mode: 'strip' });
  } catch (error) {
    throw new Error(`Type stripping failed for ${file}: ${error.message}`);
  }
}

function transformModule(root, file, source) {
  const deps = [];
  const imports = [];
  let code = stripTypes(file, source);

  const resolveDep = (spec) => {
    if (!spec.startsWith('.')) {
      throw new Error(`${toId(root, file)}: only relative imports are supported (got "${spec}")`);
    }
    const target = resolve(dirname(file), spec);
    deps.push(target);
    return toId(root, target);
  };

  code = code.replace(NAMED_IMPORT, (_m, names, _q, spec) => {
    const id = resolveDep(spec);
    const parts = names
      .split(',')
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => {
        const match = part.match(new RegExp(`^(${IDENT})(?:\\s+as\\s+(${IDENT}))?$`));
        if (!match) throw new Error(`${toId(root, file)}: unsupported import specifier "${part}"`);
        imports.push({ id, name: match[1] });
        return match[2] ? `${match[1]}: ${match[2]}` : match[1];
      });
    return `const { ${parts.join(', ')} } = __req(${JSON.stringify(id)});`;
  });
  code = code.replace(NS_IMPORT, (_m, ns, _q, spec) => `const ${ns} = __req(${JSON.stringify(resolveDep(spec))});`);
  code = code.replace(BARE_IMPORT, (_m, _q, spec) => `__req(${JSON.stringify(resolveDep(spec))});`);

  if (/^import\b/m.test(code)) {
    throw new Error(`${toId(root, file)}: unsupported import form remains after transform`);
  }

  const exported = [];
  code = code.replace(EXPORT_DECL, (_m, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });
  if (/^export\b/m.test(code)) {
    throw new Error(`${toId(root, file)}: unsupported export form (use "export function|const|let|class name")`);
  }

  const tail = exported.map((name) => `__exports.${name} = ${name};`).join('\n');
  return { code: `${code}\n${tail}\n`, deps, imports, exported };
}

/**
 * Bundles `entry` (absolute path) and its relative imports into one IIFE string.
 * @param {string} root absolute project root, used for stable module ids
 * @param {string} entry absolute path of the entry module
 * @returns {string}
 */
export function bundle(root, entry) {
  const modules = new Map();
  const visiting = new Set();

  const visit = (file, chain) => {
    if (modules.has(file)) return;
    if (visiting.has(file)) {
      throw new Error(`Import cycle: ${[...chain, file].map((f) => toId(root, f)).join(' -> ')}`);
    }
    visiting.add(file);
    const mod = transformModule(root, file, readFileSync(file, 'utf8'));
    for (const dep of mod.deps) visit(dep, [...chain, file]);
    visiting.delete(file);
    modules.set(file, mod);
  };
  visit(entry, []);

  const exportsById = new Map([...modules].map(([file, mod]) => [toId(root, file), new Set(mod.exported)]));
  for (const [file, mod] of modules) {
    for (const { id, name } of mod.imports) {
      if (!exportsById.get(id)?.has(name)) {
        throw new Error(`${toId(root, file)}: "${name}" is not a runtime export of ${id} (use "import type" for types)`);
      }
    }
  }

  const defs = [...modules]
    .map(([file, mod]) => `// --- ${toId(root, file)} ---\n${JSON.stringify(toId(root, file))}: function (__exports, __req) {\n${mod.code}}`)
    .join(',\n');

  return [
    '// Generated by src/tools/bundle.mjs from Folio TypeScript sources. Do not edit.',
    '(() => {',
    "'use strict';",
    `const __defs = {\n${defs}\n};`,
    'const __cache = {};',
    'function __req(id) {',
    '  if (__cache[id]) return __cache[id];',
    '  const exports = {};',
    '  __cache[id] = exports;',
    '  __defs[id](exports, __req);',
    '  return exports;',
    '}',
    `__req(${JSON.stringify(toId(root, entry))});`,
    '})();',
    '',
  ].join('\n');
}
