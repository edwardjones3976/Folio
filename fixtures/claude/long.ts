// SYNTHETIC long-conversation fixture generator (deterministic; no real data).
// Produces `exchanges` prompt/reply pairs using the same modelled claude.ai
// markup as the static fixtures. Exchange NEEDLE_EXCHANGE contains a unique
// phrase used by retrieval tests.

export const LONG_EXCHANGES = 250;
export const NEEDLE_EXCHANGE = 137;
export const NEEDLE_PHRASE = 'copper-kettle protocol';

const TOPICS = ['budget', 'schema', 'deployment', 'testing', 'caching', 'logging', 'billing', 'search', 'onboarding', 'backups'];
const VERBS = ['review', 'plan', 'measure', 'refactor', 'document', 'automate', 'compare', 'migrate'];

/** Small deterministic PRNG (mulberry32) so the fixture is identical on every run. */
function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pick<T>(items: readonly T[], random: () => number): T {
  return items[Math.floor(random() * items.length)]!;
}

export function longConversationHtml(exchanges = LONG_EXCHANGES): string {
  const random = prng(20261029);
  const turns: string[] = [];
  for (let i = 1; i <= exchanges; i++) {
    const topic = pick(TOPICS, random);
    const verb = pick(VERBS, random);
    const prompt = `Step ${i}: how should we ${verb} the ${topic} work for milestone ${Math.ceil(i / 10)}?`;
    const heading = i % 10 === 0 ? `<h2>Milestone ${i / 10} checkpoint</h2>` : '';
    const needle = i === NEEDLE_EXCHANGE ? ` For this step use the ${NEEDLE_PHRASE} described in the runbook.` : '';
    const reply =
      `For step ${i}, ${verb} the ${topic} work in small batches and record the outcome in the log.${needle} ` +
      `Estimated effort: ${1 + Math.floor(random() * 8)} hours.`;
    turns.push(
      `<div data-test-render-count="1" class="turn" data-fixture-exchange="${i}">` +
        `<div class="group"><div data-testid="user-message" class="font-user-message"><p>${prompt}</p></div></div></div>`,
      `<div data-test-render-count="1" class="turn" data-fixture-exchange="${i}">` +
        `<div data-is-streaming="false" class="group"><div class="font-claude-response"><div class="standard-markdown">` +
        `${heading}<p>${reply}</p></div></div></div></div>`,
    );
  }
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="folio-fixture" content="synthetic">
<title>Synthetic fixture: Long project log - Claude</title>
<style>body{margin:0;font:16px/1.5 sans-serif}.scroller{height:100vh;overflow-y:auto}.turn{max-width:720px;margin:0 auto;padding:12px}</style>
</head>
<body>
<!-- SYNTHETIC TEST FIXTURE for Folio, generated by fixtures/claude/long.ts. NOT captured from claude.ai; no real user data. -->
<div role="note">Synthetic test fixture modelled on claude.ai. Not real claude.ai content.</div>
<main class="scroller"><div class="conversation" id="conversation">
${turns.join('\n')}
</div></main>
</body>
</html>
`;
}
